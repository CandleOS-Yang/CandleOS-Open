bool shift_pressed;
bool ctrl_pressed;
bool capslock_on;
bool numlock_on;

/* 获取扫描码对应ASCII */
uint8_t scan_code_to_ascii(uint8_t scan_code) {
    if (scan_code & 0x80) {
        scan_code &= 0x7F;

        switch (scan_code)
        {
        case KEY_LSHIFT:
            shift_pressed = false;
            return 0;
        case KEY_RSHIFT:
            shift_pressed = false;
            return 0;
        case KEY_CTRL:
            ctrl_pressed = false;
            return 0;
        }
        return 0;
    }

    switch (scan_code)
    {
    case KEY_LSHIFT:
        shift_pressed = true;
        return 0;
    case KEY_RSHIFT:
        shift_pressed = true;
        return 0;
    case KEY_CTRL:
        ctrl_pressed = true;
        return 0;
    case KEY_CAPS:
        capslock_on = !capslock_on;
        printk(capslock_on ? "(CAPS ON)" : "(CAPS OFF)");
        return 0;
    case KEY_NUMLOCK:
        numlock_on = !numlock_on;
        printk(numlock_on ? "(NUM ON)" : "(NUM OFF)");
    case KEY_ENTER:
        return '\n';
    }

    if (scan_code >= 0x47 && scan_code <= 0x53 && scan_code != 0x4A && scan_code != 0x4E) {
        if (numlock_on) {
            return keyboard_map[3][scan_code];
        } else {
            return keyboard_map[3][scan_code];
        }
    }
    
    uint8_t map_idx = 0;
    if (shift_pressed ^ capslock_on) {
        map_idx = 1;
    } else if (ctrl_pressed) {
        map_idx = 2;
    }
    return keyboard_map[map_idx][scan_code];
}

/* 读取键盘LED状态 */
uint8_t read_keyboard_leds() {
    uint8_t status;
    
    while (inb(0x64) & 0x02);
    outb(0x60, 0xED);

    while (!(inb(0x64) & 0x01));
    status = inb(0x60);
    return status;
}

/* 键盘ISR处理函数 */
void keyboard_isr_handler(uint32_t vector) {
    uint8_t scan_code = inb(0x60);
    uint8_t ascii = scan_code_to_ascii(scan_code);

    printk("%c", ascii);
    send_eoi(vector);
}

/* 初始化键盘控制器 */
void keyboard_init() {
    /*
    所有的0x60这些端口号和命令要改成宏定义
    */
    set_isr_handler(0x21, (uint32_t)keyboard_isr_handler);
    uint8_t status = read_keyboard_leds();
    numlock_on = status & KBD_LED_NUM_LOCK;
    capslock_on = status & KBD_LED_CAPS_LOCK;
    shift_pressed = false;
    ctrl_pressed = false;

    enable_int_bit(0x21);

    printk("Keynboard Info\n==> NumLock: %d   CapsLock: %d\n", numlock_on, capslock_on);
    printk("Now you can input:\n");
}